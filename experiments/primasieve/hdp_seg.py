LOG = math.log
BOS = "$"                                   # utterance-boundary token (Goldwater); never generated by P0

# ---------- base distribution P0: iid phonemes x geometric length (the ONLY hand-set prior) ----------
def make_P0(streams, p_hash=0.2):
    cc = collections.Counter(); n = 0
    for s in streams:
        for c in s: cc[c] += 1; n += 1
    lpph = {c: LOG(cc[c] / n) for c in cc}
    lp_hash = LOG(p_hash); lp_cont = LOG(1 - p_hash)
    def logP0(w):
        if w == BOS: return -1e9            # structural marker: negligible base mass (dominated by its table count)
        return sum(lpph[c] for c in w) + (len(w) - 1) * lp_cont + lp_hash
    return logP0

# ---------- DP / HDP state. bigram=True -> two-level HDP; bigram=False -> single unigram DP (the control arm) ----
class DP:
    """bigram HDP:  P(w|v) = (n[v][w] + a1*P1(w))/(nc[v] + a1),  P1(w) = (b[w] + a0*P0(w))/(B + a0),
       b[w] = base table count (minimal-table approx: #distinct contexts serving w).  [documented simplification]
    unigram DP:    P(w)   = (b[w] + a0*P0(w))/(B + a0),  b[w] = TOKEN count of w  (context ignored)."""
    def __init__(self, logP0, bigram=True, a0=100.0, a1=3000.0):
        self.logP0 = logP0; self.bigram = bigram; self.a0 = a0; self.a1 = a1
        self.n = collections.defaultdict(collections.Counter); self.nc = collections.Counter()
        self.b = collections.Counter(); self.B = 0
        self._p0 = {}                        # cache exp(logP0(w))

    def p0(self, w):
        v = self._p0.get(w)
        if v is None: v = self._p0[w] = math.exp(self.logP0(w))
        return v

    def P1(self, w):
        return (self.b[w] + self.a0 * self.p0(w)) / (self.B + self.a0)

    def logpred(self, v, w):
        if not self.bigram:
            return LOG(self.P1(w))
        return LOG((self.n[v][w] + self.a1 * self.P1(w)) / (self.nc[v] + self.a1))

    def add(self, v, w):
        if not self.bigram:
            self.b[w] += 1; self.B += 1; return
        if self.n[v][w] == 0: self.b[w] += 1; self.B += 1          # new base table
        self.n[v][w] += 1; self.nc[v] += 1
    def remove(self, v, w):
        if not self.bigram:
            self.b[w] -= 1; self.B -= 1
            if self.b[w] == 0: del self.b[w]
            return
        self.n[v][w] -= 1; self.nc[v] -= 1
        if self.n[v][w] == 0:
            del self.n[v][w]; self.b[w] -= 1; self.B -= 1
            if self.b[w] == 0: del self.b[w]

    def score_span(self, words, prev, nxt):
        added = []; lp = 0.0; ctx = prev
        for w in list(words) + [nxt]:
            lp += self.logpred(ctx, w); self.add(ctx, w); added.append((ctx, w)); ctx = w
        for v, w in reversed(added): self.remove(v, w)
        return lp
    def corpus_ll(self, streams, B):
        """Plug-in predictive log-likelihood of the CURRENT segmentation under the final counts (gold-BLIND).
        A legitimate model-selection score (higher=better fit); used to pick alpha WITHOUT looking at F."""
        ll = 0.0
        for s, cuts in zip(streams, B):
            ctx = BOS
            for w in cuts_to_words(s, cuts): ll += self.logpred(ctx, w); ctx = w
            ll += self.logpred(ctx, BOS)
        return ll

    def add_span(self, words, prev, nxt):
        ctx = prev
        for w in list(words) + [nxt]: self.add(ctx, w); ctx = w
    def remove_span(self, words, prev, nxt):
        ctx = prev
        for w in list(words) + [nxt]: self.remove(ctx, w); ctx = w

# ---------- init ----------
def init_boundaries(streams, mode="entropy", seed=0):
    rng = random.Random(seed)
    if mode == "random":
        return [sorted(g for g in range(1, len(s)) if rng.random() < 0.5) for s in streams]
    if mode == "none":
        return [[] for _ in streams]
    rises = Z.entropy_rise(streams, k=4)     # entropy PROPOSAL as init (sampler does the real work)
    return [sorted(g for g in range(1, len(s)) if rises[u][g] > 0.0) for u, s in enumerate(streams)]

def cuts_to_words(s, cuts):
    pts = [0] + list(cuts) + [len(s)]
    return [s[pts[i]:pts[i + 1]] for i in range(len(pts) - 1)]

def build_state(dp, streams, B):
    for s, cuts in zip(streams, B): dp.add_span(cuts_to_words(s, cuts), BOS, BOS)

# ---------- Gibbs boundary sweep ----------
def gibbs_sweep(dp, streams, B, temp, rng):
    inv = 1.0 / temp
    for u in range(len(streams)):
        s = streams[u]; L = len(s); cutset = set(B[u])
        for i in range(1, L):
            l = i - 1
            while l > 0 and l not in cutset: l -= 1
            r = i + 1
            while r < L and r not in cutset: r += 1
            if l == 0: prev = BOS
            else:
                pl = l - 1
                while pl > 0 and pl not in cutset: pl -= 1
                prev = s[pl:l]
            if r == L: nxt = BOS
            else:
                rr = r + 1
                while rr < L and rr not in cutset: rr += 1
                nxt = s[r:rr]
            whole = s[l:r]; w1 = s[l:i]; w2 = s[i:r]; is_b = i in cutset
            if is_b: dp.remove_span([w1, w2], prev, nxt)
            else:    dp.remove_span([whole], prev, nxt)
            lp_no = dp.score_span([whole], prev, nxt)
            lp_b = dp.score_span([w1, w2], prev, nxt)
            m = max(lp_no, lp_b)
            p_no = math.exp((lp_no - m) * inv); p_b = math.exp((lp_b - m) * inv)
            if rng.random() < p_b / (p_no + p_b):
                dp.add_span([w1, w2], prev, nxt); cutset.add(i)
            else:
                dp.add_span([whole], prev, nxt); cutset.discard(i)
        B[u] = sorted(cutset)
    return B

def degeneracy(streams, B):
    toks = [w for s, cuts in zip(streams, B) for w in cuts_to_words(s, cuts)]
    ntok = len(toks); mlen = sum(len(w) for w in toks) / ntok if ntok else 0
    one = sum(1 for cuts in B if len(cuts) == 0) / len(B)
    return len(set(toks)), mlen, one

def anneal_temp(it, sweeps):                 # 10 -> 1 over the first min(120, 40% of sweeps), then hold at 1
    A = min(120.0, 0.4 * sweeps); frac = min(1.0, it / max(1.0, A)); return 10.0 - 9.0 * frac

def run(streams, gold, bigram=True, a0=100.0, a1=3000.0, sweeps=120, init="entropy", seed=0,
        report_every=10, tag=""):
    logP0 = make_P0(streams, p_hash=0.2 if bigram else 0.5)
    dp = DP(logP0, bigram, a0, a1)
    B = init_boundaries(streams, init, seed); build_state(dp, streams, B)
    rng = random.Random(seed + 1)
    f0 = Z.token_f(gold, [set(c) for c in B])[0]     # init-only F ( delta baseline)
    traj = [(0, anneal_temp(0, sweeps), f0)]
    for it in range(1, sweeps + 1):
        gibbs_sweep(dp, streams, B, anneal_temp(it, sweeps), rng)
        if it % report_every == 0 or it == sweeps:
            f, P, R = Z.token_f(gold, [set(c) for c in B])
            ty, ml, one = degeneracy(streams, B)
            traj.append((it, anneal_temp(it, sweeps), f))
            print(f"    {tag:16s} sw{it:4d} T{anneal_temp(it,sweeps):4.1f}  F={f:.3f} P={P:.3f} R={R:.3f}"
                  f" | dF_init={f-f0:+.3f}  types={ty} mlen={ml:.2f} one-word={one:.2f}")
    return B, traj, f0

